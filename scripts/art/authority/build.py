"""Build the Authority home-card illustration.

    python scripts/art/authority/build.py

Reads the flat (no grain) Gemini image from scripts/art/authority/source/flat.png, splits it into
layers (segment.py), traces each with vtracer, and writes src/dojos/authority/art/scene.ts plus a
preview SVG in scripts/art/authority/out/. The coordinates below are in the 2752 x 1536 source
image. The cage, the viewfinder corners and rec dot, her pupils and sweat, the chai steam, the
cage's floor shadow and the shorts' gingham are drawn by the component, not traced; scene.ts
carries the measurements they are drawn from.
"""

import json
import re
import subprocess
import sys
from pathlib import Path

import vtracer

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
SRC = HERE / "source" / "flat.png"
OUT = HERE / "out"
TS_OUT = ROOT / "src" / "dojos" / "authority" / "art" / "scene.ts"
VIEW_BOX = "1230 290 1510 1200"  # board, both people, the cage and the floor, with a margin

TRACE = dict(colormode="color", hierarchical="stacked", mode="spline", corner_threshold=60,
             length_threshold=4.0, max_iterations=10, splice_threshold=45, path_precision=1,
             color_precision=6, layer_difference=16)

PATH_RE = re.compile(r'<path d="([^"]+)" fill="([^"]+)" transform="translate\(([-\d.]+),([-\d.]+)\)"/>')
TOK = re.compile(r"[MCLZ]|-?\d+\.?\d*")


def trace(png: Path, speckle: int, **settings) -> list[dict]:
    svg = png.with_suffix(".svg")
    vtracer.convert_image_to_svg_py(str(png), str(svg), filter_speckle=speckle, **{**TRACE, **settings})
    out = []
    for d, fill, tx, ty in PATH_RE.findall(svg.read_text()):
        tx, ty = float(tx), float(ty)
        cmds, cur, nums = [], None, []
        for t in TOK.findall(d):
            if t in "MCLZ":
                if cur:
                    cmds.append((cur, nums))
                cur, nums = t, []
            else:
                nums.append(float(t))
        if cur:
            cmds.append((cur, nums))
        out.append({"cmds": cmds, "tx": tx, "ty": ty, "fill": fill.lower()})
    return out


def compact(p: dict) -> list[str]:
    """Absolute float path -> relative integer path, about half the bytes."""
    s, px, py, sx, sy = [], 0, 0, 0, 0
    for c, n in p["cmds"]:
        ab = [(round(x + p["tx"]), round(y + p["ty"])) for x, y in zip(n[0::2], n[1::2])]
        if c == "M":
            (x, y), = ab
            s.append(f"M{x} {y}")
            px, py, sx, sy = x, y, x, y
        elif c == "Z":
            s.append("z")
            px, py = sx, sy
        else:
            step = 3 if c == "C" else 1
            rel = []
            for i in range(0, len(ab), step):
                seg = ab[i:i + step]
                rel += [f"{x - px} {y - py}" for x, y in seg]
                px, py = seg[-1]
            s.append(c.lower() + " ".join(rel))
    return [re.sub(r" -", "-", "".join(s)), p["fill"]]


def gingham(g: dict) -> dict:
    """The shorts' check as two tints multiplied over their flat (light) base: one stripe, and two
    crossed."""
    rgb = lambda h: [int(h[i:i + 2], 16) for i in (1, 3, 5)]  # noqa: E731
    k = [s / l for s, l in zip(rgb(g["single"]), rgb(g["light"]))]
    hexc = lambda v: "#" + "".join(f"{min(255, round(c * 255)):02x}" for c in v)  # noqa: E731
    return {"stripe": hexc(k), "cross": hexc([c * c for c in k])}


def main() -> None:
    OUT.mkdir(exist_ok=True)
    subprocess.run([sys.executable, "-I", str(HERE / "segment.py"), str(SRC), str(OUT)], check=True)
    geo = json.loads((OUT / "geometry.json").read_text())

    layers = {
        # Default clustering throughout: Gemini's "flat" image still has soft gradients (faces,
        # legs, the board), and finer settings traced them as blotches.
        "BACK": trace(OUT / "back.png", 10),
        "EVIDENCE": trace(OUT / "evidence.png", 6),
        "TORSO": trace(OUT / "torso.png", 6),
        "ARM": trace(OUT / "arm.png", 6),
        "SHIN": trace(OUT / "shin.png", 6),
        "CHAPPAL": trace(OUT / "chappal.png", 6),
        "THIGH": trace(OUT / "thigh.png", 6),
        "HER": trace(OUT / "her.png", 8),
        "CABLE": trace(OUT / "cable.png", 4, color_precision=8, layer_difference=8),
        "WHITES": trace(OUT / "whites.png", 4),
        "BROWS": trace(OUT / "brows.png", 4),
        "SHORTS": trace(OUT / "shorts.png", 10),
    }

    r1 = lambda v: round(v, 1)  # noqa: E731
    measures = {
        "CAGE": geo["cage"],
        "EYES": [{k: r1(v) for k, v in e.items()} for e in geo["eyes"]],
        "PUPIL": {"dx": r1(geo["pupil"]["dx"]), "dy": r1(geo["pupil"]["dy"]), "fill": geo["pupil_colour"]},
        "SWEAT_FILL": geo["drop_colour"],
        "GINGHAM": gingham(geo["gingham"]),
    }

    ts = [
        "/* Generated by scripts/art/authority/build.py. Don't edit by hand: re-run the script. */",
        'import type { ArtPath } from "@/components/home/art";',
        "",
        f'export const VIEW_BOX = "{VIEW_BOX}";',
    ]
    docs = {
        "CAGE": "The phone-shaped cage: outline box, corner radius, stroke, bars (left edges), notch and camera.",
        "EYES": "Her eye whites as ellipses, left then right. Pupils are clipped to them.",
        "PUPIL": "Where her pupils sit at rest, relative to each eye's centre (looking down at her phone).",
        "SWEAT_FILL": "Her sweat drops.",
        "GINGHAM": "The shorts' check: tints multiplied over their flat base, one stripe and two crossed.",
    }
    for name, value in measures.items():
        ts.append(f"/** {docs[name]} */")
        ts.append(f"export const {name} = {json.dumps(value)} as const;")
    for name, paths in layers.items():
        ts.append(f"export const {name}: readonly ArtPath[] = {json.dumps([compact(p) for p in paths])};")
    TS_OUT.parent.mkdir(parents=True, exist_ok=True)
    TS_OUT.write_text("\n".join(ts) + "\n")
    subprocess.run(["npx", "prettier", "--write", str(TS_OUT)], cwd=ROOT, check=True)

    # A static preview for eyeballing the trace (no animation and none of the parts drawn in code).
    body = "".join(f'<path d="{d}" fill="{f}"/>' for k, v in layers.items() if k != "SHORTS"
                   for d, f in map(compact, v))
    (OUT / "preview.svg").write_text(
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{VIEW_BOX}" style="background:#f4e0dd">{body}</svg>')
    print(f"wrote {TS_OUT.relative_to(ROOT)} ({TS_OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
