"""Build the Trust Me Bro home-card illustration.

    python scripts/art/trust-me-bro/build.py

Reads the flat (no grain) Gemini image from scripts/art/trust-me-bro/source/flat.png, splits it
into layers (segment.py), traces each with vtracer, and writes src/dojos/trust-me-bro/art/scene.ts
plus a preview SVG in scripts/art/trust-me-bro/out/. The coordinates below are in the 2752 x 1536
source image. The string, its blips and the pay button are drawn by the component, not traced.
"""

import json
import re
import subprocess
import sys
from pathlib import Path

import vtracer

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
SRC = HERE / "source" / "flat.png"
OUT = HERE / "out"
TS_OUT = ROOT / "src" / "dojos" / "trust-me-bro" / "art" / "scene.ts"
VIEW_BOX = "1250 300 1420 1170"  # wall, both people and their floor shadows, with a margin

TRACE = dict(colormode="color", hierarchical="stacked", mode="spline", corner_threshold=60,
             length_threshold=4.0, max_iterations=10, splice_threshold=45, path_precision=1,
             color_precision=6, layer_difference=16)
LEFT_EYE = 1633  # whites and pupils whose right edge is left of this belong to the left eye

PATH_RE = re.compile(r'<path d="([^"]+)" fill="([^"]+)" transform="translate\(([-\d.]+),([-\d.]+)\)"/>')
TOK = re.compile(r"[MCLZ]|-?\d+\.?\d*")


def trace(png: Path, speckle: int, **settings) -> list[dict]:
    svg = png.with_suffix(".svg")
    vtracer.convert_image_to_svg_py(str(png), str(svg), filter_speckle=speckle, **{**TRACE, **settings})
    out = []
    for d, fill, tx, ty in PATH_RE.findall(svg.read_text()):
        tx, ty = float(tx), float(ty)
        cmds, cur, nums = [], None, []
        for t in TOK.findall(d):
            if t in "MCLZ":
                if cur:
                    cmds.append((cur, nums))
                cur, nums = t, []
            else:
                nums.append(float(t))
        if cur:
            cmds.append((cur, nums))
        pts = [(x + tx, y + ty) for _, n in cmds for x, y in zip(n[0::2], n[1::2])]
        xs, ys = [p[0] for p in pts], [p[1] for p in pts]
        out.append({"cmds": cmds, "tx": tx, "ty": ty, "fill": fill.lower(),
                    "bbox": (min(xs), min(ys), max(xs), max(ys))})
    return out


def compact(p: dict) -> list[str]:
    """Absolute float path -> relative integer path, about half the bytes."""
    s, px, py, sx, sy = [], 0, 0, 0, 0
    for c, n in p["cmds"]:
        ab = [(round(x + p["tx"]), round(y + p["ty"])) for x, y in zip(n[0::2], n[1::2])]
        if c == "M":
            (x, y), = ab
            s.append(f"M{x} {y}")
            px, py, sx, sy = x, y, x, y
        elif c == "Z":
            s.append("z")
            px, py = sx, sy
        else:
            step = 3 if c == "C" else 1
            rel = []
            for i in range(0, len(ab), step):
                seg = ab[i:i + step]
                rel += [f"{x - px} {y - py}" for x, y in seg]
                px, py = seg[-1]
            s.append(c.lower() + " ".join(rel))
    return [re.sub(r" -", "-", "".join(s)), p["fill"]]


def main() -> None:
    OUT.mkdir(exist_ok=True)
    subprocess.run([sys.executable, "-I", str(HERE / "segment.py"), str(SRC), str(OUT)], check=True)

    whites, pupils = trace(OUT / "whites.png", 4), trace(OUT / "pupils.png", 4)
    left = lambda p: p["bbox"][2] < LEFT_EYE  # noqa: E731
    layers = {
        "FLOOR": trace(OUT / "floor.png", 10),
        # Finest clustering for the back: at coarser settings the hoodie's dark hem band, the
        # jeans' waistband and the phone's lilac edge merged into their neighbours.
        "BACK": trace(OUT / "back.png", 10, color_precision=8, layer_difference=5),
        "CUTOUT": trace(OUT / "cutout.png", 6, color_precision=7, layer_difference=10),
        "FIST": trace(OUT / "fist.png", 6),
        "HEAD": trace(OUT / "head.png", 6, color_precision=7, layer_difference=10),
        "ARM": trace(OUT / "arm.png", 6, color_precision=7, layer_difference=10),
        "THUMB": trace(OUT / "thumb.png", 4),
    }
    eyes = {
        "WHITES": [[p for p in whites if left(p)], [p for p in whites if not left(p)]],
        "PUPILS": [[p for p in pupils if left(p)], [p for p in pupils if not left(p)]],
    }

    def arr(paths: list[dict]) -> str:
        return json.dumps([compact(p) for p in paths])

    ts = [
        "/* Generated by scripts/art/trust-me-bro/build.py. Don't edit by hand: re-run the script. */",
        'import type { ArtPath } from "@/components/home/art";',
        "",
        f'export const VIEW_BOX = "{VIEW_BOX}";',
    ]
    for name, paths in layers.items():
        ts.append(f"export const {name}: readonly ArtPath[] = {arr(paths)};")
    for name, pair in eyes.items():
        ts.append(f"export const {name}: readonly (readonly ArtPath[])[] = [{', '.join(arr(e) for e in pair)}];")
    TS_OUT.parent.mkdir(parents=True, exist_ok=True)
    TS_OUT.write_text("\n".join(ts) + "\n")
    subprocess.run(["npx", "prettier", "--write", str(TS_OUT)], cwd=ROOT, check=True)

    # A static preview for eyeballing the trace (no animation, no string or pay button).
    groups = [layers["FLOOR"], layers["BACK"], *eyes["WHITES"], *eyes["PUPILS"], layers["CUTOUT"],
              layers["FIST"], layers["HEAD"], layers["ARM"], layers["THUMB"]]
    body = "".join(f'<path d="{d}" fill="{f}"/>' for g in groups for d, f in map(compact, g))
    (OUT / "preview.svg").write_text(
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{VIEW_BOX}" style="background:#e6ddf2">{body}</svg>')
    print(f"wrote {TS_OUT.relative_to(ROOT)} ({TS_OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
